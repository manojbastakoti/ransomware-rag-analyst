"""Human-in-the-loop approval for sensitive containment recommendations.

Any checklist item with ``requires_approval=True`` (actions that affect accounts, hosts, network
paths or external communication) stays "PENDING APPROVAL" until a named analyst approves it with a
justification. Every decision is written to logs/approvals.jsonl as an audit trail.
"""
from __future__ import annotations

import copy
import time

from .monitoring import log_event


class ApprovalError(ValueError):
    pass


def apply_decisions(checklist: dict, approved_ids: list[str], analyst: str, justification: str,
                    rejected_ids: list[str] | None = None) -> dict:
    analyst, justification = (analyst or "").strip(), (justification or "").strip()
    rejected_ids = rejected_ids or []
    if (approved_ids or rejected_ids) and not analyst:
        raise ApprovalError("Analyst name is required to approve or reject actions.")
    if approved_ids and len(justification) < 10:
        raise ApprovalError("Please give a short justification (at least 10 characters) for the approval.")
    out = copy.deepcopy(checklist)
    ts = time.strftime("%Y-%m-%d %H:%M")
    by_id = {it["id"]: it for it in out["items"]}
    for cid in approved_ids + rejected_ids:
        it = by_id.get(cid)
        if it is None:
            raise ApprovalError(f"Unknown checklist item {cid}")
        if not it["requires_approval"]:
            continue
        decision = "approved" if cid in approved_ids else "rejected"
        it["status"] = f"{decision.upper()} by {analyst} ({ts})"
        it["decision"] = decision
        log_event({"type": "approval", "item": cid, "action": it["action"], "technique": it["technique"],
                   "decision": decision, "analyst": analyst, "justification": justification}, name="approvals.jsonl")
    out["n_pending_approval"] = sum(1 for it in out["items"] if it["status"] == "PENDING APPROVAL")
    out["approved"] = [it["id"] for it in out["items"] if it.get("decision") == "approved"]
    out["rejected"] = [it["id"] for it in out["items"] if it.get("decision") == "rejected"]
    return out


def checklist_to_markdown(checklist: dict, title: str = "Ransomware Defensive Checklist") -> str:
    lines = [f"# {title}", "",
             "_Generated by the Ransomware Threat Intelligence RAG Analyst (Group 3B). Containment steps marked "
             "PENDING APPROVAL must not be executed until approved by an authorised analyst._", ""]
    phase = None
    for it in checklist["items"]:
        if it["phase"] != phase:
            phase = it["phase"]
            lines += ["", f"## {phase}", ""]
        box = "x" if it["status"].startswith("APPROVED") else " "
        flag = f" — **{it['status']}**" if it["requires_approval"] else ""
        lines.append(f"- [{box}] **{it['id']}** {it['action']} _(technique: {it['technique']}; source: {it['source']})_{flag}")
    return "\n".join(lines) + "\n"
